"""Generate correctness goldens from the official ISO 532-1:2017 Annex A C program.

Reference program (decision D4, phase plan 0.4.0 D-D): the official
`ISO_532-1.c` (SHA-256 pinned below) with exactly one table cell changed,
USL[12][4] 0.22f -> 0.24f (`tools/golden-c-usl12-4.diff`), compiled with MSVC
x64 `/O2 /fp:precise`. The unmodified official file is compiled as well; its
outputs are kept next to the golden for the `unmodified_c_delta` record.

The generated wrapper only calls the public entry points
`f_loudness_from_signal` (time-varying) and `f_loudness_from_levels`
(stationary); no DSP code is changed.

Signals:
  * the nine signals of tools/gen_golden.py, read from data/golden/<name>/sig.bin
    (bitwise the input the Rust golden tests use);
  * Annex B signals 18/23/24/25 (the C-01 tail points), decoded from the ISO
    archive like the official CLI: PCM16 / 32768, times the Annex C 60 dB
    calibration factor (sequential intensity sum, as ISO_532-1_main.c).

Time-varying output grid (C-01 contract, iso532::zwtv_out_frames): for L input
samples the Rust result has ceil(L/96) points, point j = internal 2 kHz frame 4j
at time 96j/48000 s. The C program writes floor(L/24) internal frames, so it
runs on the input followed by zeros up to 96*(ceil(L/96)+1) samples; the tool
checks that every internal frame of the unpadded run is bitwise identical in the
padded run (prefix invariance) before using it.

Stationary: the C stationary entry from levels is fed the 28 third-octave levels
of data/golden/<name>/spec_third_db.bin (the MoSQITo noct_spectrum front end the
Rust stationary path ports); the Rust test feeds the same levels to
main_loudness + calc_slopes. The stationary front end is not part of this golden.

Output layout: data/golden-c/<name>/*.bin (little-endian f64, specific loudness
bark-major [240][n] like iso532 `n_specific`), data/golden-c/meta.json, and the
manifest tools/golden-c.sha256.

Run (Windows, MSVC 2022 x64):
  .venv/Scripts/python tools/gen_golden_c.py --official <ISO_532-1.c> \
      --header <ISO_532-1.h> --vcvars <vcvars64.bat> --iso-archive <official dir> \
      --out data/golden-c/
"""
import argparse
import ctypes as ct
import datetime as dt
import difflib
import hashlib
import json
import math
import os
import platform
import shutil
import subprocess
import sys
import wave
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
OFFICIAL_SHA256 = "a74b45ed297cd09ac60701a923120341137d227e536f3109ae4ece810d834491"
DIFF_FILE = ROOT / "tools" / "golden-c-usl12-4.diff"
MANIFEST = ROOT / "tools" / "golden-c.sha256"
CL_FLAGS = ["/nologo", "/O2", "/fp:precise", "/LD"]
FS = 48000

# Row 12 of the USL table (RNS range 0.30-0.22 sone/Bark); column 4 is the cell.
USL_ROW12_OFFICIAL = b"    { 0.40f,0.33f,0.26f,0.24f,0.22f,0.22f,0.22f,0.22f},"
USL_ROW12_GOLDEN = b"    { 0.40f,0.33f,0.26f,0.24f,0.24f,0.22f,0.22f,0.22f},"

GOLDEN_SIGNALS = [
    "sine_1k_60",
    "sine_250_80",
    "sine_4k_60",
    "white_60",
    "pulse_1k_70",
    "step_60_80",
    "annexb_sig3",
    "annexb_sig5",
    "annexb_sig10",
]
C01_SIGNALS = {
    18: "Test signal 18 (hammer).wav",
    23: "Test signal 23 (typewriter).wav",
    24: "Test signal 24 (woodpecker).wav",
    25: "Test signal 25 (full can rattle).wav",
}
CALIBRATION_WAV = ("Annex C", "calibration signal sine 1kHz 60dB.wav")
CALIBRATION_DB = 60.0
I_REF = 4e-10
# Calibration factor bits recorded by the 2026-11-03 C-01 zero-pad round.
C01_ZERO_PAD_FACTOR_BITS = "4006afb6b68fc829"

WRAPPER_C = r"""/* Generated by tools/gen_golden_c.py. Calls the public Annex A entry points only. */
#include "ISO_532-1.c"
#define API __declspec(dllexport)

API int gc_time_varying(double *x, int len, double *total, double *spec, int k)
{
    struct InputData in;
    double *rows[N_BARK_BANDS];
    int b;
    in.NumSamples = len;
    in.SampleRate = 48000;
    in.pData = x;
    for (b = 0; b < N_BARK_BANDS; b++)
        rows[b] = spec + (size_t)b * k;
    return f_loudness_from_signal(&in, SoundFieldFree, LoudnessMethodTimeVarying,
                                  0, total, rows, k);
}

API int gc_stationary_levels(const double *levels, double *total, double *spec)
{
    double work[N_LEVEL_BANDS];
    double *lev[N_LEVEL_BANDS];
    double *rows[N_BARK_BANDS];
    int b;
    for (b = 0; b < N_LEVEL_BANDS; b++) {
        work[b] = levels[b];
        lev[b] = &work[b];
    }
    for (b = 0; b < N_BARK_BANDS; b++)
        rows[b] = spec + b;
    return f_loudness_from_levels(lev, 1, SoundFieldFree, LoudnessMethodStationary,
                                  total, rows);
}
"""

DP = ct.POINTER(ct.c_double)


def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def sha256_file(p: Path) -> str:
    return sha256_bytes(p.read_bytes())


def fail(msg: str):
    sys.exit(f"gen_golden_c: {msg}")


def make_golden_source(official: bytes) -> tuple[bytes, str]:
    if official.count(USL_ROW12_OFFICIAL) != 1:
        fail("USL row 12 not found exactly once in the official source")
    golden = official.replace(USL_ROW12_OFFICIAL, USL_ROW12_GOLDEN)
    a = official.decode("utf-8").replace("\r\n", "\n").split("\n")
    b = golden.decode("utf-8").replace("\r\n", "\n").split("\n")
    diff = "".join(
        line + "\n"
        for line in difflib.unified_diff(a, b, "a/ISO_532-1.c", "b/ISO_532-1.c", lineterm="")
    )
    changed = [ln for ln in diff.splitlines() if ln[:1] in "+-" and ln[:3] not in ("+++", "---")]
    if len(changed) != 2:
        fail(f"expected a one-line change, got {changed}")
    return golden, diff


def check_diff_file(diff: str):
    if not DIFF_FILE.exists():
        fail(f"missing {DIFF_FILE.relative_to(ROOT)}")
    committed = DIFF_FILE.read_text(encoding="utf-8").replace("\r\n", "\n")
    if committed != diff:
        fail(f"{DIFF_FILE.relative_to(ROOT)} differs from the substitution this tool applies")


def run_vcvars(vcvars: Path, cmd: str, cwd: Path) -> subprocess.CompletedProcess:
    full = f'call "{vcvars}" >nul && {cmd}'
    env = dict(os.environ, VSLANG="1033")  # English compiler messages
    return subprocess.run(full, shell=True, cwd=cwd, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", env=env)


def compiler_banner(vcvars: Path, cwd: Path) -> str:
    r = run_vcvars(vcvars, "cl", cwd)
    lines = [ln.strip() for ln in (r.stderr + r.stdout).splitlines() if ln.strip()]
    banner = next((ln for ln in lines if "Compiler Version" in ln), None)
    if banner is None:
        fail(f"cannot read the MSVC version banner: {lines[:3]}")
    return banner


def build(vcvars: Path, header: bytes, source: bytes, build_dir: Path) -> Path:
    if build_dir.exists():
        shutil.rmtree(build_dir)
    build_dir.mkdir(parents=True)
    (build_dir / "ISO_532-1.h").write_bytes(header)
    (build_dir / "ISO_532-1.c").write_bytes(source)
    (build_dir / "golden_c_wrapper.c").write_text(WRAPPER_C, encoding="utf-8", newline="\n")
    cmd = "cl " + " ".join(CL_FLAGS) + " /I. golden_c_wrapper.c /link /OUT:golden_c.dll"
    r = run_vcvars(vcvars, cmd, build_dir)
    (build_dir / "build.log").write_text(r.stdout + r.stderr, encoding="utf-8")
    if r.returncode != 0 or not (build_dir / "golden_c.dll").exists():
        fail(f"build failed in {build_dir} (exit {r.returncode}):\n{r.stdout}{r.stderr}")
    return build_dir / "golden_c.dll"


class CLib:
    def __init__(self, dll: Path):
        self.lib = ct.CDLL(str(dll))
        self.lib.gc_time_varying.argtypes = [DP, ct.c_int, DP, DP, ct.c_int]
        self.lib.gc_time_varying.restype = ct.c_int
        self.lib.gc_stationary_levels.argtypes = [DP, DP, DP]
        self.lib.gc_stationary_levels.restype = ct.c_int

    def time_varying(self, x: np.ndarray):
        x = np.ascontiguousarray(x, dtype="<f8").copy()
        k = len(x) // 24
        total = np.zeros(k)
        spec = np.zeros((240, k))
        got = self.lib.gc_time_varying(
            x.ctypes.data_as(DP), len(x), total.ctypes.data_as(DP), spec.ctypes.data_as(DP), k
        )
        if got != k:
            fail(f"f_loudness_from_signal returned {got}, expected {k}")
        return total, spec

    def stationary(self, levels: np.ndarray):
        levels = np.ascontiguousarray(levels, dtype="<f8")
        if levels.shape != (28,):
            fail(f"stationary levels must have 28 values, got {levels.shape}")
        total = np.zeros(1)
        spec = np.zeros(240)
        got = self.lib.gc_stationary_levels(
            levels.ctypes.data_as(DP), total.ctypes.data_as(DP), spec.ctypes.data_as(DP)
        )
        if got != 1:
            fail(f"f_loudness_from_levels returned {got}, expected 1")
        return total, spec


def out_frames(n_samples: int) -> int:
    # iso532::zwtv_out_frames: ceil(ceil(L/24)/4)
    return -(-(-(-n_samples // 24)) // 4)


def time_varying_on_grid(clib: CLib, x: np.ndarray):
    """C internal frames 4j, j < ceil(L/96), from a zero-padded run, with the
    prefix-invariance check against the unpadded run."""
    n = len(x)
    n_out = out_frames(n)
    padded_len = 96 * (-(-n // 96) + 1)
    xp = np.zeros(padded_len)
    xp[:n] = x
    t_raw, s_raw = clib.time_varying(x)
    t_pad, s_pad = clib.time_varying(xp)
    k0 = len(t_raw)
    prefix_ok = bool(
        np.array_equal(t_raw.view("u8"), t_pad[:k0].view("u8"))
        and np.array_equal(s_raw.view("u8"), s_pad[:, :k0].view("u8"))
    )
    if not prefix_ok:
        fail("C output of the unpadded run is not a bitwise prefix of the padded run")
    idx = 4 * np.arange(n_out)
    if idx[-1] >= len(t_pad):
        fail("padding too short for the output grid")
    time = np.array([(96 * j) / 48000.0 for j in range(n_out)])
    info = {
        "samples": n,
        "out_frames": n_out,
        "padded_samples": padded_len,
        "c_internal_frames_unpadded": k0,
        "c_internal_frames_padded": len(t_pad),
        "prefix_invariance_bitwise": prefix_ok,
    }
    return t_pad[idx].copy(), np.ascontiguousarray(s_pad[:, idx]), time, info


def read_wav_pcm16(p: Path) -> np.ndarray:
    with wave.open(str(p), "rb") as w:
        params = (w.getnchannels(), w.getsampwidth(), w.getframerate())
        if params != (1, 2, FS):
            fail(f"{p.name}: expected mono PCM16 48 kHz, got {params}")
        raw = w.readframes(w.getnframes())
    return np.frombuffer(raw, dtype="<i2").astype(np.float64) / 32768


def calibration_factor(cal: np.ndarray) -> float:
    # ISO_532-1_main.c: IntensSum += pow(x, 2) in sample order; /= N;
    # CalFactor = sqrt(pow(10, Level/10) * I_REF / IntensSum).
    s = 0.0
    for v in cal.tolist():
        s += v * v
    s /= len(cal)
    return math.sqrt(math.pow(10.0, CALIBRATION_DB / 10.0) * I_REF / s)


def dump(d: Path, name: str, arr) -> dict:
    a = np.ascontiguousarray(np.asarray(arr, dtype="<f8"))
    p = d / f"{name}.bin"
    a.tofile(p)
    return {"shape": list(a.shape), "sha256": sha256_file(p)}


def write_manifest(out: Path):
    files = sorted(
        p for p in out.rglob("*")
        if p.is_file() and p.suffix in (".bin", ".json") and "_build" not in p.relative_to(out).parts
    )
    lines = [
        "# data/golden-c manifest written by tools/gen_golden_c.py (Annex A C reference,",
        "# USL[12][4] = 0.24f). Bytes depend only on the official C program, MSVC and the",
        "# inputs listed in meta.json; meta.json also carries the generation date.",
    ]
    for p in files:
        lines.append(f"{sha256_file(p)}  {p.relative_to(out).as_posix()}")
    MANIFEST.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--official", type=Path, required=True, help="official ISO_532-1.c")
    ap.add_argument("--header", type=Path, required=True, help="official ISO_532-1.h")
    ap.add_argument("--vcvars", type=Path, required=True, help="MSVC vcvars64.bat")
    ap.add_argument("--iso-archive", type=Path, required=True,
                    help="extracted ISO 532-1 archive root (holds 'Annex B.5' and 'Annex C')")
    ap.add_argument("--out", type=Path, default=ROOT / "data" / "golden-c")
    args = ap.parse_args()

    official = args.official.read_bytes()
    official_sha = sha256_bytes(official)
    if official_sha != OFFICIAL_SHA256:
        fail(f"official source SHA-256 {official_sha} != pinned {OFFICIAL_SHA256}")
    header = args.header.read_bytes()
    golden_src, diff = make_golden_source(official)
    check_diff_file(diff)

    golden_dir = ROOT / "data" / "golden"
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    build_root = out / "_build"
    banner = compiler_banner(args.vcvars, out)
    lib_golden = CLib(build(args.vcvars, header, golden_src, build_root / "usl12-4-024"))
    lib_official = CLib(build(args.vcvars, header, official, build_root / "official"))

    meta = {
        "tool": "tools/gen_golden_c.py",
        "generated": dt.datetime.now(dt.timezone(dt.timedelta(hours=8))).isoformat(timespec="seconds"),
        "reference": "ISO 532-1:2017 Annex A C program, USL[12][4] 0.22f -> 0.24f (only change)",
        "official_source_sha256": official_sha,
        "official_header_sha256": sha256_bytes(header),
        "golden_source_sha256": sha256_bytes(golden_src),
        "substitution_diff": DIFF_FILE.relative_to(ROOT).as_posix(),
        "substitution_diff_sha256": sha256_file(DIFF_FILE),
        "wrapper_sha256": sha256_bytes(WRAPPER_C.encode("utf-8")),
        "compiler": banner,
        "compiler_flags": " ".join(CL_FLAGS),
        "dll_sha256": {
            "usl12-4-024": sha256_file(build_root / "usl12-4-024" / "golden_c.dll"),
            "official": sha256_file(build_root / "official" / "golden_c.dll"),
        },
        "python": platform.python_version(),
        "numpy": np.__version__,
        "layout": "little-endian f64; specific loudness bark-major [240][n]",
        "time_varying_grid": "point j = C internal frame 4j of the zero-padded run, time 96j/48000 s",
        "files": {
            "zwtv_total / zwtv_specific / zwtv_time": "golden (0.24f) time-varying output on the Rust grid",
            "zwtv_total_official / zwtv_specific_official": "same grid, unmodified official C",
            "zwst_levels": "28 third-octave levels fed to f_loudness_from_levels (stationary)",
            "zwst_total / zwst_specific": "golden (0.24f) stationary output",
            "zwst_total_official / zwst_specific_official": "unmodified official C, stationary",
        },
        "signals": {},
    }

    def emit(name: str, x: np.ndarray, source: dict, levels: np.ndarray | None):
        d = out / name
        d.mkdir(exist_ok=True)
        entry = {"source": source}
        entry["sig"] = dump(d, "sig", x)
        tg, sg, time, info = time_varying_on_grid(lib_golden, x)
        to, so, time_o, info_o = time_varying_on_grid(lib_official, x)
        assert np.array_equal(time, time_o) and info == info_o
        entry["grid"] = info
        entry["zwtv_total"] = dump(d, "zwtv_total", tg)
        entry["zwtv_specific"] = dump(d, "zwtv_specific", sg)
        entry["zwtv_time"] = dump(d, "zwtv_time", time)
        entry["zwtv_total_official"] = dump(d, "zwtv_total_official", to)
        entry["zwtv_specific_official"] = dump(d, "zwtv_specific_official", so)
        entry["golden_minus_official"] = {
            "zwtv_total_max_abs": float(np.abs(tg - to).max()),
            "zwtv_specific_max_abs": float(np.abs(sg - so).max()),
        }
        if levels is not None:
            stg, ssg = lib_golden.stationary(levels)
            sto, sso = lib_official.stationary(levels)
            entry["zwst_levels"] = dump(d, "zwst_levels", levels)
            entry["zwst_total"] = dump(d, "zwst_total", stg)
            entry["zwst_specific"] = dump(d, "zwst_specific", ssg)
            entry["zwst_total_official"] = dump(d, "zwst_total_official", sto)
            entry["zwst_specific_official"] = dump(d, "zwst_specific_official", sso)
            entry["golden_minus_official"]["zwst_total_abs"] = float(abs(stg[0] - sto[0]))
            entry["golden_minus_official"]["zwst_specific_max_abs"] = float(np.abs(ssg - sso).max())
        meta["signals"][name] = entry
        print(f"done {name}: {len(x)} samples, {info['out_frames']} points", flush=True)
        return tg, sg, to, so

    for name in GOLDEN_SIGNALS:
        sig_path = golden_dir / name / "sig.bin"
        lev_path = golden_dir / name / "spec_third_db.bin"
        if not sig_path.exists() or not lev_path.exists():
            fail(f"missing {sig_path} or {lev_path} (run tools/gen_golden.py first)")
        x = np.fromfile(sig_path, dtype="<f8")
        levels = np.fromfile(lev_path, dtype="<f8")
        emit(name, x, {"golden_sig_bin_sha256": sha256_file(sig_path),
                       "levels": f"data/golden/{name}/spec_third_db.bin",
                       "levels_sha256": sha256_file(lev_path)}, levels)

    cal_path = args.iso_archive.joinpath(*CALIBRATION_WAV)
    if not cal_path.exists():
        fail(f"missing calibration file {CALIBRATION_WAV}")
    factor = calibration_factor(read_wav_pcm16(cal_path))
    factor_bits = np.float64(factor).view("u8").item().to_bytes(8, "big").hex()
    meta["calibration"] = {
        "file": "/".join(CALIBRATION_WAV),
        "file_sha256": sha256_file(cal_path),
        "level_db": CALIBRATION_DB,
        "factor": repr(factor),
        "factor_bits": factor_bits,
        "matches_c01_zero_pad_round": factor_bits == C01_ZERO_PAD_FACTOR_BITS,
    }
    tails = {}
    for sig, wav_name in C01_SIGNALS.items():
        wav_path = args.iso_archive / "Annex B.5" / wav_name
        if not wav_path.exists():
            fail(f"missing Annex B.5/{wav_name}")
        x = read_wav_pcm16(wav_path) * factor
        tg, sg, to, so = emit(f"annexb_c01_sig{sig}", x,
                              {"wav": f"Annex B.5/{wav_name}", "wav_sha256": sha256_file(wav_path)}, None)
        tails[f"signal_{sig}"] = {
            "point": len(tg) - 1,
            "golden_total": repr(float(tg[-1])),
            "official_total": repr(float(to[-1])),
            "golden_minus_official_total": float(tg[-1] - to[-1]),
            "golden_minus_official_specific_max_abs": float(np.abs(sg[:, -1] - so[:, -1]).max()),
        }
    meta["unmodified_c_delta"] = {
        "meaning": "C-01 tail point (last output point): golden C (USL[12][4] = 0.24f) minus "
                   "the unmodified official C (0.22f). Rust 0.4.0 equals the golden to <= 1e-10 "
                   "(tests/golden_c.rs), so this is also Rust minus unmodified C to that precision.",
        "tails": tails,
        "max_abs_total": max(abs(v["golden_minus_official_total"]) for v in tails.values()),
    }

    (out / "meta.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8", newline="\n")
    write_manifest(out)
    print(f"wrote {out} and {MANIFEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
